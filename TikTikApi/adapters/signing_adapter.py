"""
Signing Adapter - Output Port Implementation

What it does:
    Implements the SigningPort protocol using Playwright's browser context
    to execute TikTik's JavaScript signing function (window.byted_acrawler.frontierSign).

How it works:
    1. Waits for TikTik's `byted_acrawler` JavaScript to load in the browser
    2. Calls the `frontierSign(url)` function to generate the X-Bogus parameter
    3. Returns the signed URL back to the application layer

Why:
    TikTik's anti-bot system requires every API request to include an X-Bogus
    signature. This signature is generated by obfuscated JavaScript running in
    a real browser context. The signing adapter encapsulates this complexity:
    - The application just calls sign_url() and gets a signed URL
    - Multiple signing attempts with different TikTik pages as fallback
    - Automatic session recovery if the browser dies during signing
"""

from __future__ import annotations

import random
from typing import Optional

from playwright.async_api import (
    TimeoutError as PlaywrightTimeoutError,
    Error as PlaywrightError,
)

from ..adapters.playwright_browser import PlaywrightBrowserAdapter


class SigningAdapter:
    """
    SigningPort implementation using Playwright browser JavaScript execution.

    Generates X-Bogus signatures by executing TikTik's obfuscated JS in browser context.
    """

    def __init__(self, browser_adapter: PlaywrightBrowserAdapter):
        self._browser = browser_adapter

    async def generate_x_bogus(self, url: str, session_index: Optional[int] = None) -> dict:
        """Generate the X-Bogus value for a URL."""
        _, session = await self._browser.get_valid_session(session_index)

        max_attempts = 5
        for attempt in range(max_attempts):
            try:
                timeout_time = random.randint(5000, 20000)
                await session.page.wait_for_function("window.byted_acrawler !== undefined", timeout=timeout_time)
                break
            except PlaywrightTimeoutError:
                if attempt == max_attempts - 1:
                    raise PlaywrightTimeoutError(f"Failed to load TikTik signing JS after {max_attempts} attempts")
                try_urls = ["https://www.TikTik.com/foryou", "https://www.TikTik.com", "https://www.TikTik.com/@TikTik"]
                await session.page.goto(random.choice(try_urls))
            except PlaywrightError as e:
                self._browser._logger.error(f"Session died during x-bogus: {e}")
                await self._browser.invalidate_session(session)
                raise

        try:
            return await session.page.evaluate(f'() => {{ return window.byted_acrawler.frontierSign("{url}") }}')
        except PlaywrightError as e:
            self._browser._logger.error(f"Session died during x-bogus eval: {e}")
            await self._browser.invalidate_session(session)
            raise

    async def sign_url(self, url: str, session_index: Optional[int] = None) -> str:
        """Add the X-Bogus signature to a URL."""
        i, session = await self._browser.get_valid_session(session_index)
        x_bogus = (await self.generate_x_bogus(url, session_index=i)).get("X-Bogus")
        if x_bogus is None:
            raise Exception("Failed to generate X-Bogus")
        separator = "&" if "?" in url else "?"
        return f"{url}{separator}X-Bogus={x_bogus}"
