"""
Signing Port - Outbound Interface for Request Signing

What it does:
    Defines the contract for TikTik's anti-bot request signing (X-Bogus).
    Every request to TikTik's API must include a signed URL with the X-Bogus
    parameter, which is generated by executing JavaScript in a browser context.

Why:
    The X-Bogus signing mechanism is TikTik-specific and may change. By
    abstracting it behind this port, the signing algorithm can be updated
    without changing application code.
"""

from __future__ import annotations

from typing import Optional, Protocol


class SigningPort(Protocol):
    """Protocol for TikTik request signing."""

    async def sign_url(
        self,
        url: str,
        session_index: Optional[int] = None,
    ) -> str: ...

    async def generate_x_bogus(
        self,
        url: str,
        session_index: Optional[int] = None,
    ) -> dict: ...
